class Solution:
    def missingnumber(self, nums: list[int]) -> int:
        n = len(nums)
        range_sum = n * (n + 1) // 2
        list_sum = sum(nums)
        return range_sum - list_sum

class Solution:
    def reverseArray(self, nums: list[int]) -> int:
        left = 0
        right = len(nums) - 1
        while left < right:
            nums[left], nums[right] = nums[right], nums[left]
            left += 1
            right -= 1
        return nums

class Solution:
    def removeElement(self, nums: list[int], val: int) -> int:
        k = 0

        for i in range(len(nums)):
            if nums[i] != val:
                nums[k] = nums[i]
                k += 1

        return k

